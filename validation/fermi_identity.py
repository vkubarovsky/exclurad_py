#!/usr/bin/env python3
"""Acceptance criterion 1: fermi = none must change NOTHING.

Generates the same small sample twice -- once through the code as it is, once
with the Fermi flag explicitly off -- and compares the sha256 of the LUND
bytes.  Run this before every commit on this branch.  It is the single test
that keeps the branch from interfering with the running campaign: if it
passes, a production card cannot notice that the deuteron code exists.

The mechanism it protects: _draw_fermi() returns before touching self.rng when
the flag is off, so the random stream is bit-for-bit the free-nucleon one.
Any future edit that draws a number unconditionally will fail here.

    python3 validation/fermi_identity.py [nev]
"""

import hashlib
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np  # noqa: E402

from exclurad_py import models  # noqa: E402
from exclurad_py.generator.events import Box, Generator  # noqa: E402
from exclurad_py.generator.lund import write_lund  # noqa: E402


def sample(fermi, nev, seed=20260925):
    sf = models.get("pi0.amp2609", t_nucl=-0.30)
    sf.Ebeam = 10.6
    g = Generator(sf, Ebeam=10.6,
                  box=Box(Q2=(1.0, 5.0), W2=(4.5, 12.0), t=(-2.0, -0.10)),
                  mx2_cut=sf.mU ** 2 + 0.20, helicity=0, seed=seed,
                  born_only=True, fermi=fermi,
                  majorant_shape=(4, 4, 4, 6))
    g.setup()
    ev = g.generate(nev)
    path = Path(tempfile.mkdtemp()) / "out.lund"
    write_lund(str(path), ev, sf.channel, topology=sf.topology)
    return hashlib.sha256(path.read_bytes()).hexdigest(), ev, g


def _production_head():
    """Resolve production's head AT RUN TIME.

    It used to be the literal "16412f8", the commit this branch forked from.
    That rots the moment production moves -- and it rots SILENTLY: the test
    still passes, against a tree that is no longer what anyone is merging
    into, so it proves nothing while looking green.  (Suggested by the session
    running the production branch, 2026-09-26.)
    """
    import subprocess
    root = Path(__file__).resolve().parent.parent
    for ref in ("origin/production", "production"):
        try:
            return subprocess.run(["git", "rev-parse", ref], cwd=root,
                                  capture_output=True, text=True,
                                  check=True).stdout.strip()
        except subprocess.CalledProcessError:
            continue
    raise RuntimeError("cannot resolve production's head; is this a git checkout?")


PRODUCTION = _production_head()


def production_hash(nev):
    """Same sample, generated by the production branch in a throwaway worktree.

    Comparing two runs of THIS code only proves determinism.  The criterion is
    identity with production, so production has to actually run.
    """
    import subprocess
    wt = Path(tempfile.mkdtemp()) / "prod"
    root = Path(__file__).resolve().parent.parent
    try:
        subprocess.run(["git", "worktree", "add", "--detach", "-q",
                        str(wt), PRODUCTION], cwd=root, check=True,
                       capture_output=True)
    except subprocess.CalledProcessError as exc:
        print(f"  (could not check out {PRODUCTION}: "
              f"{exc.stderr.decode().strip()})")
        return None
    try:
        r = subprocess.run([sys.executable, str(Path(__file__).with_name(
            "_fermi_ref_sample.py")), str(wt), str(nev)],
            capture_output=True, text=True, check=True)
        return r.stdout.strip().splitlines()[-1]
    finally:
        subprocess.run(["git", "worktree", "remove", "--force", str(wt)],
                       cwd=root, capture_output=True)


def main():
    nev = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    h_ref, ev_ref, _ = sample("none", nev)
    h_prod = production_hash(nev)
    print(f"production {PRODUCTION}    sha256 {h_prod}")
    print(f"this branch, none   sha256 {h_ref}")
    ok = (h_prod is None) or (h_prod == h_ref)
    print("byte-identical:     " + ("YES" if h_prod == h_ref else
                                    ("SKIPPED" if h_prod is None
                                     else "NO  <-- FAIL")))

    # ... and the deuteron run must differ, or the flag does nothing
    h_d, ev_d, g_d = sample("av18", nev)
    print(f"\nfermi=av18          sha256 {h_d}")
    print("differs from none:  " + ("YES" if h_d != h_ref else "NO  <-- FAIL"))
    print(f"fermi rejects:      {g_d.n_fermi_reject} trials "
          f"({g_d.n_fermi_reject / max(g_d.n_trials, 1):.3%} of trials)")
    p = np.array([e["p_fermi"] for e in ev_d])
    print(f"p_F in the sample:  <|p|> = {p.mean()*1000:.1f} MeV/c, "
          f"rms {np.sqrt((p**2).mean())*1000:.1f}, max {p.max()*1000:.1f}")
    return 0 if (ok and h_d != h_ref) else 1


if __name__ == "__main__":
    sys.exit(main())
