#!/bin/bash
# Боевой прогон prod-pi0-v1: пи-ноль с до-вершинным внешним излучением.
#
#   run_prod_v1.sh <код> <каталог вывода> <база зерна> <ядер> <рубеж-epoch> <метка> [канал]
#
# Канал -- седьмой и необязательный, по умолчанию pi0: старые вызовы должны
# продолжать работать слово в слово.  Один скрипт на все каналы намеренно:
# второй скрипт означал бы второй набор защит, а они здесь все выстраданы.
# Объёмы задаются через NEV_RAD/NEV_BORN в окружении.
#
# Каталог вывода задаётся ПРЯМО и целиком: что написали, там и будет.  В
# первой редакции скрипт приписывал к нему своё имя, и на ферме вышло
# exclurad_py_work/prod_pi0_v1 внутри exclurad_py рядом с exclurad_py --
# разобраться было нельзя.
#
# Один скрипт на три машины.  Каждый круг -- своё зерно и свой каталог,
# поэтому образцы разных машин и разных кругов СКЛАДЫВАЮТСЯ.
#
# Устройство каталога (единое везде):
#   <каталог вывода>/
#       README.md          что это, каким кодом, какой коробкой
#       card_rad.txt       карточки, по одной на режим
#       card_born.txt
#       part_runner.py     пишется скриптом, снаружи ничего не нужно
#       cyc01/ cyc02/ ...  круги: lund/ и logs/ внутри
#       STOP               создать -- петля закончит круг и выйдет
#
# ОСТАНОВКА -- ТОЛЬКО ФАЙЛОМ.  Убивать надзирателя нельзя: он живёт в tmux,
# и pkill по имени валит сессию, а та по SIGHUP -- всю группу вместе с
# воркерами.  Так за неделю трижды пропал идущий счёт.  `touch STOP` --
# петля доработает круг и выйдет сама.
set -u
REPO=$1; OUT=$2; BASE=$3; J=$4; DEADLINE=$5; TAG=$6; CH=${7:-pi0}
NEV_RAD=${NEV_RAD:-100000}
NEV_BORN=${NEV_BORN:-$((NEV_RAD * 5))}
# Секунд на одно радиационное событие на ядро -- только для оценки "влезет
# ли круг до рубежа".  Ошибка здесь стоит недосчитанного круга, не порчи.
SEC_RAD=${SEC_RAD:-26}          # десятые доли секунды
# --- надзор за зависшей частью ------------------------------------------
# `wait` без предела -- это то, чем оборачивается зависшая часть: круг стоит
# вечно, рубеж проходит мимо, и никто не узнаёт.  Так уже вышло девять часов
# простоя на J/psi у порога (тупик в завершении пула процессов, python 3.14).
#
# Признак зависания -- НЕ молчание лога: части со второй по N-ю не печатают
# ничего до самого конца, у них лог молчит всегда.  Признак -- остановка
# потребления процессора: тупик в блокировке тактов не жжёт, а медленный
# счёт жжёт.  Это ловит ровно тот случай и не трогает просто долгие части.
STALL_S=${STALL_S:-2400}         # столько секунд без прироста CPU -- снимаем
# 900 с оказалось мало.  25.08 на ферме так снялись пять частей борновского
# круга: три успели записать файл и висели уже в завершении -- эти снятия
# чистый выигрыш, -- а две встали НА ЗАПИСИ, в четырёх событиях от конца, и
# оставили файлы нулевого размера.  Потеряно 41667 событий из 500000.
# Lustre под нагрузкой может держать запись минутами, и убивать за это
# нельзя; многочасовое зависание 2400 с ловит так же надёжно.
PART_MAX_H=${PART_MAX_H:-12}     # абсолютный предел на часть, часов
# Карточку можно назвать явно (env CARD).  Иначе берётся rad_<канал>.txt.
# Нужно для отдельных исследований -- например, ро под разбивку статьи по BSA,
# где коробка и обрезание свои, а канал тот же.
CARD=${CARD:-$REPO/cards/rad_$CH.txt}
[ -f "$CARD" ] || { echo "нет карточки $CARD"; exit 1; }

STOP=$OUT/STOP
mkdir -p "$OUT"
rm -f "$STOP"

cd "$REPO"; export PYTHONPATH=$REPO
export TABLE_SERIAL=1 ETA_PROPOSAL_CAP=5 EXACT_ACCEPT=1 EXPO_TAIL=1

# Сетка и запас мажоранты -- ПО КАНАЛУ.
#
# Сетка: у J/psi сечение меняется по Q2 в миллион раз поперёк коробки, и
# сетка по умолчанию его не облегает -- 8,8,8,12 даёт 7.5 % эффективности
# против 18.8 % у 16,8,16,12.  Клетка вдвое дороже в сборке и в двенадцать
# раз дешевле в счёте.
#
# Запас: 4.0 стоял глобально из-за rho, у которого мажоранта пробивалась.
# Он входит в эффективность прямым делителем, то есть 4.0 стоит нам 2.5-кратного
# замедления.  Померено 24.08 на J/psi (250 событий на точку, сетка
# 16,8,16,12): запас 4.0 -> 4.77 %, 2.5 -> 7.60 %, 1.6 -> 11.56 %, и во всех
# трёх НИ ОДНОГО пробоя.  При 1.2 появляются первые два из 7506 проб
# (макс превышение x1.075).  Значит 1.6 -- край, где ещё чисто.
# Остальным каналам оставлен 4.0: для них это не мерено.
# Померено 24.08, 250-300 событий на точку:
#   J/psi (сетка 16,8,16,12): 4.0 -> 4.77 %, 2.5 -> 7.60 %, 1.6 -> 11.56 %,
#     все три без пробоев; при 1.2 первые два из 7506 (макс x1.075).
#   phi (сетка по умолчанию): 4.0 -> 7.85 %, 2.5 -> 12.13 %, 1.6 -> 19.04 %,
#     1.2 -> 25.45 % -- НИ ОДНОГО пробоя даже при 1.2.
# Обоим ставим 1.6: у J/psi это край чистого, у phi -- запас сверх края,
# и выборки в триста событий мало, чтобы идти до 1.2.
# rho остаётся на 4.0: именно у него мажоранта пробивалась.
case "$CH" in
  jpsi) MAJ_SHAPE=${MAJ_SHAPE:-16,8,16,12}; MAJ_SAFETY=${MAJ_SAFETY:-1.6} ;;
  phi)  MAJ_SHAPE=${MAJ_SHAPE:-};           MAJ_SAFETY=${MAJ_SAFETY:-1.6} ;;
  *)    MAJ_SHAPE=${MAJ_SHAPE:-};           MAJ_SAFETY=${MAJ_SAFETY:-4.0} ;;
esac
export MAJ_SAFETY
[ -n "$MAJ_SHAPE" ] && export MAJ_SHAPE || unset MAJ_SHAPE

# Запускалка одной части -- пишем её сами.  Раньше она лежала снаружи, и
# перенос каталога ломал прогон.
cat > "$OUT/part_runner.py" <<'PYRUN'
import sys
from exclurad_py.run import run
card, ipart, npart, seed = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
run(card, verbose=(ipart == 1), _part=(ipart, npart, seed))
PYRUN

VER=$(python3 -c "from exclurad_py.provenance import git_hash, git_tag; print(git_hash(), git_tag())" 2>/dev/null || echo "unknown unknown")
# Версия считается ЗДЕСЬ, один раз, где git заведомо работает, и передаётся
# частям через окружение.  Внутри части git может не отработать -- 25.08 так
# вышло у девяти slurm-частей из 551, и они записались безымянными.
export EXCLURAD_COMMIT=${VER%% *} EXCLURAD_TAG=${VER##* }
export EXCLURAD_BRANCH=$(git -C "$REPO" rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)

# README пишется КАЖДЫЙ запуск, а не только первый.  Раньше он создавался
# при отсутствии -- чтобы не затирать, -- и перезапуск с другим NEV_RAD или
# другой сеткой мажоранты оставлял старые числа при новых кругах.  Это сводит
# на нет то, ради чего коробка вообще перенесена из прозы в текст, порождаемый
# из карточки.  Предыдущая редакция не пропадает: она уезжает в README_prev.
if [ -f "$OUT/README.md" ]; then
  cp "$OUT/README.md" "$OUT/README_prev_$(date +%Y%m%d_%H%M%S).md"
fi
if true; then
  # Коробка берётся ИЗ КАРТОЧКИ, а не переписывается сюда руками: описание,
  # разошедшееся с тем, чем считали, хуже отсутствующего.
  BOX=$(python3 - "$CARD" <<'BOXPY'
import pathlib, sys
names = {1: "модель", 2: "E пучка, ГэВ", 5: "W2, ГэВ^2", 6: "Q2, ГэВ^2",
         7: "t, ГэВ^2", 8: "v_cut, ГэВ^2", 14: "y", 15: "xB", 16: "каты",
         17: "v_min, ГэВ^2", 18: "itarg", 19: "вершина z, см"}
k = 0
for line in pathlib.Path(sys.argv[1]).read_text().splitlines():
    v = line.split("!")[0].strip()
    if not v:
        continue
    k += 1
    if k in names:
        print("* %-16s %s" % (names[k] + ":", v))
BOXPY
)
  cat > "$OUT/README.md" <<EOF
# $CH -- боевая выборка, код $VER

Машина: $TAG ($(hostname)), ядер $J
Начато: $(date '+%Y-%m-%d %H:%M %Z')
Событий за круг: $NEV_RAD радиационных, $NEV_BORN борновских
Сетка мажоранты: ${MAJ_SHAPE:-по умолчанию 8,8,8,12}, запас $MAJ_SAFETY

## Что это

Эксклюзивное рождение $CH на протоне с ПОЛНОЙ внутренней радиационной
поправкой и с ДО-ВЕРШИННЫМ ВНЕШНИМ излучением в пятисантиметровой мишени
жидкого водорода.

Внешнее излучение выходной ноги здесь НЕ моделируется намеренно: его
