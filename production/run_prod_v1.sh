# Надзор за частями.  Возвращает число снятых.
# Массивы ТОЛЬКО индексные: на mac mini /bin/bash версии 3.2, там нет
# declare -A, и ассоциативный массив тихо превратился бы в скаляр.
supervise () {
  local pids=("$@")
  local n=${#pids[@]} t0 now i p cpu alive killed=0
  local -a last_cpu last_change
  t0=$(date +%s)
  for ((i = 0; i < n; i++)); do last_cpu[$i]=""; last_change[$i]=$t0; done
  local last_moan=0
  while :; do
    alive=0
    n_stalled=0
    now=$(date +%s)
    # ПЕРВЫЙ проход: обновить счётчики и сосчитать, сколько стоит.
    for ((i = 0; i < n; i++)); do
      p=${pids[$i]}
      [ -z "$p" ] && continue
      kill -0 "$p" 2>/dev/null || { pids[$i]=""; continue; }
      alive=$((alive + 1))
      cpu=$(ps -o time= -p "$p" 2>/dev/null | tr -d ' ')
      if [ "$cpu" != "${last_cpu[$i]}" ]; then
        last_cpu[$i]=$cpu
        last_change[$i]=$now
      fi
      [ $((now - ${last_change[$i]})) -gt "$STALL_S" ] && n_stalled=$((n_stalled + 1))
    done
    # ВТОРОЙ проход: решать.
    for ((i = 0; i < n; i++)); do
      p=${pids[$i]}
      [ -z "$p" ] && continue
      kill -0 "$p" 2>/dev/null || { pids[$i]=""; continue; }
      if [ $((now - ${last_change[$i]})) -gt "$STALL_S" ]; then
        # Если стоят ВСЕ части разом -- это не зависание части, это машина:
        # ноутбук ушёл в сон, файловая система встала, узел вытеснен.
        # Убивать в этом случае нельзя ни одну.  26.08 так погиб целый
        # радиационный круг J/psi на ноутбуке: тот заснул, десять частей
        # подряд перестали жечь такты, надзор снял все десять, и защита от
        # пустого круга уронила петлю.  Двенадцать часов счёта.
        if [ "$n_stalled" -ge "$alive" ]; then
          if [ $((now - last_moan)) -gt 900 ]; then
            echo "@@@ $TAG ВСЕ $alive частей стоят -- похоже, встала машина (сон? диск?), НЕ снимаю"
            last_moan=$now
          fi
          continue
        fi
        echo "@@@ $TAG ЗАВИСАНИЕ: часть $((i + 1)) (pid $p) не жжёт процессор ${STALL_S} с -- снимаю"
      elif [ $((now - t0)) -gt $((PART_MAX_H * 3600)) ]; then
        echo "@@@ $TAG ПРЕДЕЛ: часть $((i + 1)) (pid $p) идёт больше ${PART_MAX_H} ч -- снимаю"
      else
        continue
      fi
      # Только этот pid.  Групповой сигнал уносит tmux вместе со всем счётом.
      kill -TERM "$p" 2>/dev/null
      sleep 5
      kill -KILL "$p" 2>/dev/null
      pids[$i]=""
      killed=$((killed + 1))
    done
    [ "$alive" -eq 0 ] && break
    sleep 15
  done
  return $killed
}

mkcard () {   # $1=iborn $2=nev $3=имя
  python3 - "$1" "$2" "$OUT/$3" "$CARD" <<'PY'
import re, pathlib, sys
ib, nev, dst = sys.argv[1:4]
k = 0; out = []
for line in pathlib.Path(sys.argv[4]).read_text().splitlines():
    if line.split("!")[0].strip():
        k += 1
        if   k == 3:  line = re.sub(r'^\s*\S+', "%-34s" % nev, line, count=1)
        elif k == 4:  line = re.sub(r'^\s*\S+', "%-34s" % ib, line, count=1)
        elif k == 13: line = re.sub(r'^\s*\S+', "%-34s" % "PLACEHOLDER", line, count=1)
    out.append(line)
pathlib.Path(dst).write_text("\n".join(out) + "\n")
PY
}
mkcard 0 $NEV_RAD card_rad.txt
mkcard 1 $NEV_BORN card_born.txt

# нумерация продолжается с последнего круга: перезапуск ничего не затирает
n=$(ls -d "$OUT"/cyc* 2>/dev/null | sed 's/.*cyc//' | sort -n | tail -1)
n=$((10#${n:-0}))

while [ "$(date +%s)" -lt "$DEADLINE" ]; do
  [ -f "$STOP" ] && { echo "@@@ $TAG STOP -- выхожу, кругов сделано $n"; break; }
  n=$((n+1))
  W=$OUT/cyc$(printf %02d $n)
  mkdir -p "$W/logs"
  # ~2.6 с/событие на ядро для радиационных, борновские в десять раз дешевле
  need=$(( (NEV_RAD * SEC_RAD / 10 + NEV_BORN * SEC_RAD / 100) / J + 900 ))
  left=$(( DEADLINE - $(date +%s) ))
  if [ $left -lt $need ]; then
    echo "@@@ $TAG круг $n не влезает ($need нужно, $left осталось) -- стоп"
    rmdir "$W/logs" "$W" 2>/dev/null; n=$((n-1)); break
  fi

  for mode in born rad; do
    [ $mode = born ] && { ib=1; off=5300; } || { ib=0; off=7700; }
    sed "s|PLACEHOLDER|$W|" "$OUT/card_$mode.txt" > "$W/card_$mode.txt"
    echo "@@@ $TAG круг $n $mode начато $(date '+%d.%m %H:%M')"
    PIDS=()
    for i in $(seq 1 $J); do
      python3 -u "$OUT/part_runner.py" "$W/card_$mode.txt" $i $J \
              $((BASE + n*310000 + off*i)) > "$W/logs/${mode}_$i.log" 2>&1 &
      PIDS+=($!)
      # Первая часть строит и кэширует таблицу eta; ждём ИМЕННО её файл.
      # majorant.npz не появится никогда -- его пишет run_parallel, а части
      # зовут run(_part=...), который кэш только читает.  У born таблицы нет.
      if [ $i -eq 1 ] && [ $mode = rad ]; then
        for _ in $(seq 1 900); do
          ls "$W"/$CH/*/etatable.npz >/dev/null 2>&1 && break
          kill -0 $! 2>/dev/null || break
          sleep 3
        done; sleep 5
      fi
    done
    supervise "${PIDS[@]}"
    nkill=$?
    wait
    if [ "$nkill" -gt 0 ]; then
      echo "@@@ $TAG ВНИМАНИЕ: снято частей $nkill из $J в круге $n режима $mode"
    fi
    # Считаем файлы ТОЛЬКО текущего режима.  Раньше считался весь круг, и
    # провалившаяся радиационная часть рапортовала количество борновских:
    # 22.08 круг 1 на ферме отчитался "24 файлов" при нуле записанных
    # радиационных, и защита от пустого круга это пропустила.
    # Считаем только НЕПУСТЫЕ файлы.  Часть, снятая на записи, оставляет файл
    # в ноль байт: он попадал в счёт, и круг рапортовал полный набор при
    # потерянных событиях.
    nf=$(find "$W/$CH" -path "*_${mode}_v1/lund/*.lund" -size +0c 2>/dev/null | wc -l | tr -d ' ')
    nempty=$(find "$W/$CH" -path "*_${mode}_v1/lund/*.lund" -size 0c 2>/dev/null | wc -l | tr -d ' ')
    echo "@@@ $TAG круг $n $mode готово $(date '+%d.%m %H:%M'): $nf файлов$([ "${nempty:-0}" -gt 0 ] && echo " (+$nempty ПУСТЫХ -- события потеряны)"); $(grep -h 'health:' "$W/logs/${mode}_1.log" | tail -1)"
    # Круг без файлов -- поломка, а не "мало посчиталось".  22.08 петля так
    # прокрутила 826 пустых кругов за два с половиной часа: карточки были
    # новые, разборщик старый, каждый воркер падал за секунду.
    if [ "$nf" -eq 0 ]; then
      echo "@@@ $TAG ОСТАНОВ: круг $n режим $mode не дал ни одного файла"
      tail -5 "$W/logs/${mode}_1.log" 2>/dev/null | sed 's/^/    /'
      exit 1
    fi
  done
done
echo "@@@ $TAG ПЕТЛЯ ЗАВЕРШЕНА, кругов $n, $(date '+%d.%m %H:%M')"
