#!/bin/bash
# Боевой прогон prod-pi0-v1: пи-ноль с до-вершинным внешним излучением.
#
#   run_prod_v1.sh <код> <каталог вывода> <база зерна> <ядер> <рубеж-epoch> <метка> [канал]
#
# Канал -- седьмой и необязательный, по умолчанию pi0: старые вызовы должны
# продолжать работать слово в слово.  Один скрипт на все каналы намеренно:
# второй скрипт означал бы второй набор защит, а они здесь все выстраданы.
# Объёмы задаются через NEV_RAD/NEV_BORN в окружении.
#
# Каталог вывода задаётся ПРЯМО и целиком: что написали, там и будет.  В
# первой редакции скрипт приписывал к нему своё имя, и на ферме вышло
# exclurad_py_work/prod_pi0_v1 внутри exclurad_py рядом с exclurad_py --
# разобраться было нельзя.
#
# Один скрипт на три машины.  Каждый круг -- своё зерно и свой каталог,
# поэтому образцы разных машин и разных кругов СКЛАДЫВАЮТСЯ.
#
# Устройство каталога (единое везде):
#   <каталог вывода>/
#       README.md          что это, каким кодом, какой коробкой
#       card_rad.txt       карточки, по одной на режим
#       card_born.txt
#       part_runner.py     пишется скриптом, снаружи ничего не нужно
#       cyc01/ cyc02/ ...  круги: lund/ и logs/ внутри
#       STOP               создать -- петля закончит круг и выйдет
#
# ОСТАНОВКА -- ТОЛЬКО ФАЙЛОМ.  Убивать надзирателя нельзя: он живёт в tmux,
# и pkill по имени валит сессию, а та по SIGHUP -- всю группу вместе с
# воркерами.  Так за неделю трижды пропал идущий счёт.  `touch STOP` --
# петля доработает круг и выйдет сама.
set -u
REPO=$1; OUT=$2; BASE=$3; J=$4; DEADLINE=$5; TAG=$6; CH=${7:-pi0}
NEV_RAD=${NEV_RAD:-100000}
NEV_BORN=${NEV_BORN:-$((NEV_RAD * 5))}
# Секунд на одно радиационное событие на ядро -- только для оценки "влезет
# ли круг до рубежа".  Ошибка здесь стоит недосчитанного круга, не порчи.
SEC_RAD=${SEC_RAD:-26}          # десятые доли секунды
[ -f "$REPO/cards/rad_$CH.txt" ] || { echo "нет карточки cards/rad_$CH.txt"; exit 1; }

STOP=$OUT/STOP
mkdir -p "$OUT"
rm -f "$STOP"

cd "$REPO"; export PYTHONPATH=$REPO
export TABLE_SERIAL=1 ETA_PROPOSAL_CAP=5 EXACT_ACCEPT=1 EXPO_TAIL=1 MAJ_SAFETY=4.0

# Сетка мажоранты -- по каналу.  У J/psi сечение меняется по Q2 в миллион
# раз поперёк коробки, и сетка по умолчанию его не облегает: 8,8,8,12 даёт
# 7.5 % эффективности против 18.8 % у 16,8,16,12.  Клетка вдвое дороже в
# сборке и в двенадцать раз дешевле в счёте.
case "$CH" in
  jpsi) MAJ_SHAPE=${MAJ_SHAPE:-16,8,16,12} ;;
  *)    MAJ_SHAPE=${MAJ_SHAPE:-} ;;
esac
[ -n "$MAJ_SHAPE" ] && export MAJ_SHAPE || unset MAJ_SHAPE

# Запускалка одной части -- пишем её сами.  Раньше она лежала снаружи, и
# перенос каталога ломал прогон.
cat > "$OUT/part_runner.py" <<'PYRUN'
import sys
from exclurad_py.run import run
card, ipart, npart, seed = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
run(card, verbose=(ipart == 1), _part=(ipart, npart, seed))
PYRUN

VER=$(python3 -c "from exclurad_py.provenance import git_hash, git_tag; print(git_hash(), git_tag())" 2>/dev/null || echo "unknown unknown")

# README пишется КАЖДЫЙ запуск, а не только первый.  Раньше он создавался
# при отсутствии -- чтобы не затирать, -- и перезапуск с другим NEV_RAD или
# другой сеткой мажоранты оставлял старые числа при новых кругах.  Это сводит
# на нет то, ради чего коробка вообще перенесена из прозы в текст, порождаемый
# из карточки.  Предыдущая редакция не пропадает: она уезжает в README_prev.
if [ -f "$OUT/README.md" ]; then
  cp "$OUT/README.md" "$OUT/README_prev_$(date +%Y%m%d_%H%M%S).md"
fi
if true; then
  # Коробка берётся ИЗ КАРТОЧКИ, а не переписывается сюда руками: описание,
  # разошедшееся с тем, чем считали, хуже отсутствующего.
  BOX=$(python3 - "$REPO/cards/rad_$CH.txt" <<'BOXPY'
import pathlib, sys
names = {1: "модель", 2: "E пучка, ГэВ", 5: "W2, ГэВ^2", 6: "Q2, ГэВ^2",
         7: "t, ГэВ^2", 8: "v_cut, ГэВ^2", 14: "y", 15: "xB", 16: "каты",
         17: "v_min, ГэВ^2", 18: "itarg", 19: "вершина z, см"}
k = 0
for line in pathlib.Path(sys.argv[1]).read_text().splitlines():
    v = line.split("!")[0].strip()
    if not v:
        continue
    k += 1
    if k in names:
        print("* %-16s %s" % (names[k] + ":", v))
BOXPY
)
  cat > "$OUT/README.md" <<EOF
# $CH -- боевая выборка, код $VER

Машина: $TAG ($(hostname)), ядер $J
Начато: $(date '+%Y-%m-%d %H:%M %Z')
Событий за круг: $NEV_RAD радиационных, $NEV_BORN борновских
Сетка мажоранты: ${MAJ_SHAPE:-по умолчанию 8,8,8,12}, запас $MAJ_SAFETY

## Что это

Эксклюзивное рождение $CH на протоне с ПОЛНОЙ внутренней радиационной
поправкой и с ДО-ВЕРШИННЫМ ВНЕШНИМ излучением в пятисантиметровой мишени
жидкого водорода.

Внешнее излучение выходной ноги здесь НЕ моделируется намеренно: его
считает Geant4 в GEMC, и повторять его тут значило бы посчитать дважды.
Входную ногу может дать только генератор -- Geant4 стартует с вершины и
энергию пучка получает готовой.

## Коробка

$BOX

## На чём стоит эта версия

* радиатор сверен с exclugen: доля событий, выбитых за обрезание
  эксклюзивности, 0.800 +- 0.026 % против 0.873 +- 0.112 % у exclugen;
* при itarg=0 выше обрезания НОЛЬ событий из сорока тысяч;
* целостность LUND: четырёхимпульс сходится до 1.25e-8 ГэВ, распад до 1e-10;
* воспроизводимость: тот же засев даёт побайтово тот же файл;
* для rho и phi масса мезона разыгрывается по Брейту-Вигнеру и проведена
  через кинематику, границы по t, борновское сечение и rc_factor; спектр
  масс замкнут против независимой квадратуры (rho chi2/N = 0.69 по 24
  бинам, phi 0.52 по 18);
* пи-ноль на этом теге выходит ПОБАЙТОВО тем же, что на prod-pi0-v1, --
  проверено, поэтому выборки двух тегов сравнимы.

## Оговорка про обрезание

v_cut накладывается в ИСТИННЫХ переменных, при собственной энергии события.
Анализ будет резать по ВОССТАНОВЛЕННОЙ недостающей массе, считая энергию
пучка номинальной, и около 0.8 % событий этот рез не пройдут.  Так и должно
быть: внешняя потеря только УВЕЛИЧИВАЕТ восстановленную неупругость
(v_вос - v_ист = 2 dE (E_X - p_Xz) >= 0), поэтому события уходят из окна
наружу и никогда внутрь -- выборка полна.

При v_cut = 0 хвост идёт до кинематического предела.  Это сделано нарочно:
из такой выборки любой кат вырезается потом, тогда как выборку, посчитанную
с катом, расширить обратно нельзя.

## Как остановить

    touch $OUT/STOP

Петля закончит текущий круг и выйдет.  Не убивайте процессы.
EOF
  echo "@@@ $TAG README записан, код $VER, канал $CH, сетка ${MAJ_SHAPE:-по умолчанию}"
fi

mkcard () {   # $1=iborn $2=nev $3=имя
  python3 - "$1" "$2" "$OUT/$3" "$REPO/cards/rad_$CH.txt" <<'PY'
import re, pathlib, sys
ib, nev, dst = sys.argv[1:4]
k = 0; out = []
for line in pathlib.Path(sys.argv[4]).read_text().splitlines():
    if line.split("!")[0].strip():
        k += 1
        if   k == 3:  line = re.sub(r'^\s*\S+', "%-34s" % nev, line, count=1)
        elif k == 4:  line = re.sub(r'^\s*\S+', "%-34s" % ib, line, count=1)
        elif k == 13: line = re.sub(r'^\s*\S+', "%-34s" % "PLACEHOLDER", line, count=1)
    out.append(line)
pathlib.Path(dst).write_text("\n".join(out) + "\n")
PY
}
mkcard 0 $NEV_RAD card_rad.txt
mkcard 1 $NEV_BORN card_born.txt

# нумерация продолжается с последнего круга: перезапуск ничего не затирает
n=$(ls -d "$OUT"/cyc* 2>/dev/null | sed 's/.*cyc//' | sort -n | tail -1)
n=$((10#${n:-0}))

while [ "$(date +%s)" -lt "$DEADLINE" ]; do
  [ -f "$STOP" ] && { echo "@@@ $TAG STOP -- выхожу, кругов сделано $n"; break; }
  n=$((n+1))
  W=$OUT/cyc$(printf %02d $n)
  mkdir -p "$W/logs"
  # ~2.6 с/событие на ядро для радиационных, борновские в десять раз дешевле
  need=$(( (NEV_RAD * SEC_RAD / 10 + NEV_BORN * SEC_RAD / 100) / J + 900 ))
  left=$(( DEADLINE - $(date +%s) ))
  if [ $left -lt $need ]; then
    echo "@@@ $TAG круг $n не влезает ($need нужно, $left осталось) -- стоп"
    rmdir "$W/logs" "$W" 2>/dev/null; n=$((n-1)); break
  fi

  for mode in born rad; do
    [ $mode = born ] && { ib=1; off=5300; } || { ib=0; off=7700; }
    sed "s|PLACEHOLDER|$W|" "$OUT/card_$mode.txt" > "$W/card_$mode.txt"
    echo "@@@ $TAG круг $n $mode начато $(date '+%d.%m %H:%M')"
    for i in $(seq 1 $J); do
      python3 -u "$OUT/part_runner.py" "$W/card_$mode.txt" $i $J \
              $((BASE + n*310000 + off*i)) > "$W/logs/${mode}_$i.log" 2>&1 &
      # Первая часть строит и кэширует таблицу eta; ждём ИМЕННО её файл.
      # majorant.npz не появится никогда -- его пишет run_parallel, а части
      # зовут run(_part=...), который кэш только читает.  У born таблицы нет.
      if [ $i -eq 1 ] && [ $mode = rad ]; then
        for _ in $(seq 1 900); do
          ls "$W"/$CH/*/etatable.npz >/dev/null 2>&1 && break
          kill -0 $! 2>/dev/null || break
          sleep 3
        done; sleep 5
      fi
    done
    wait
    # Считаем файлы ТОЛЬКО текущего режима.  Раньше считался весь круг, и
    # провалившаяся радиационная часть рапортовала количество борновских:
    # 22.08 круг 1 на ферме отчитался "24 файлов" при нуле записанных
    # радиационных, и защита от пустого круга это пропустила.
    nf=$(ls "$W"/$CH/*_${mode}_v1/lund/*.lund 2>/dev/null | wc -l | tr -d ' ')
    echo "@@@ $TAG круг $n $mode готово $(date '+%d.%m %H:%M'): $nf файлов; $(grep -h 'health:' "$W/logs/${mode}_1.log" | tail -1)"
    # Круг без файлов -- поломка, а не "мало посчиталось".  22.08 петля так
    # прокрутила 826 пустых кругов за два с половиной часа: карточки были
    # новые, разборщик старый, каждый воркер падал за секунду.
    if [ "$nf" -eq 0 ]; then
      echo "@@@ $TAG ОСТАНОВ: круг $n режим $mode не дал ни одного файла"
      tail -5 "$W/logs/${mode}_1.log" 2>/dev/null | sed 's/^/    /'
      exit 1
    fi
  done
done
echo "@@@ $TAG ПЕТЛЯ ЗАВЕРШЕНА, кругов $n, $(date '+%d.%m %H:%M')"
