#!/usr/bin/env python3
"""Regenerate the sample catalog at the top of the wd_14tb exclurad_py tree.

    python3 production/make_catalog.py [/Volumes/wd_14tb/exclurad_py]

Walks <model>/<channel>/<sample>/manifest.csv, sums events per mode, reads the
box from one LUND header, and rewrites catalog.csv and the "Samples" table in
README.md (between the SAMPLES-BEGIN / SAMPLES-END markers; everything else in
the README -- the layout description and the hand-written log -- is kept).
The catalog is derived from what is on the disk, never typed by hand.
"""
import csv
import glob
import os
import re
import sys
import time

ROOT = sys.argv[1] if len(sys.argv) > 1 else "/Volumes/wd_14tb/exclurad_py"


def header(path):
    kv = {}
    with open(path) as fh:
        for line in fh:
            if not line.startswith("#"):
                break
            m = re.match(r"#\s*([\w.]+):\s*(.*)$", line.strip())
            if m:
                kv[m.group(1)] = m.group(2)
    return kv


rows = []
for man in sorted(glob.glob(f"{ROOT}/*/*/*/manifest.csv")):
    sdir = os.path.dirname(man)
    model, channel, sample = sdir.split("/")[-3:]
    ev = {"born": 0, "rad": 0}; files = 0; spins = set(); hosts = set(); tags = set()
    with open(man) as fh:
        for r in csv.DictReader(fh):
            ev[r["mode"]] += int(r["events"]); files += 1
            spins.add(f"{r['beam_helicity']}/{r['target_pol']}")
            hosts.update(h.strip() for h in r["hosts"].split(";"))
    lund = next(iter(glob.glob(f"{sdir}/*/*/*/*.lund")), None)
    kv = header(lund) if lund else {}
    tags = set(t.strip() for t in kv.get("merge.version_tag", kv.get("version_tag", "")).split(";") if t.strip())
    box = lambda k: kv.get(k, "").strip("[]").replace(" ", "")
    rows.append(dict(model=model, channel=channel, sample=sample,
                     ebeam=kv.get("run.Ebeam", ""), Q2=box("run.box.Q2"), W2=box("run.box.W2"),
                     t=box("run.box.t"), vcut=kv.get("run.vcut", ""),
                     spins=" ".join(sorted(spins)), n_spin_states=len(spins),
                     born_events=ev["born"], rad_events=ev["rad"], files=files,
                     hosts=" ".join(sorted(hosts)), code_tags=" ".join(sorted(tags)),
                     merged=kv.get("merge.date", ""), path=os.path.relpath(sdir, ROOT),
                     status="complete"))

fields = ["model", "channel", "sample", "ebeam", "Q2", "W2", "t", "vcut", "spins", "n_spin_states",
          "born_events", "rad_events", "files", "hosts", "code_tags", "merged", "path", "status"]
with open(f"{ROOT}/catalog.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=fields); w.writeheader(); w.writerows(rows)

tbl = ["| model | channel | sample | spin states | born | rad | files | hosts |",
       "|---|---|---|---:|---:|---:|---:|---|"]
for r in rows:
    tbl.append(f"| {r['model']} | {r['channel']} | `{r['sample']}` | {r['n_spin_states']} | "
               f"{r['born_events']/1e6:.2f} M | {r['rad_events']/1e6:.2f} M | {r['files']} | {r['hosts']} |")
tbl.append(f"| | | **total** | | **{sum(r['born_events'] for r in rows)/1e6:.2f} M** | "
           f"**{sum(r['rad_events'] for r in rows)/1e6:.2f} M** | {sum(r['files'] for r in rows)} | |")
block = "<!-- SAMPLES-BEGIN (generated by make_catalog.py, do not edit) -->\n" + "\n".join(tbl) + \
        f"\n\n_catalog regenerated {time.strftime('%Y-%m-%d %H:%M')}_\n<!-- SAMPLES-END -->"
rp = f"{ROOT}/README.md"
txt = open(rp).read() if os.path.exists(rp) else ""
if "SAMPLES-BEGIN" in txt:
    txt = re.sub(r"<!-- SAMPLES-BEGIN.*?SAMPLES-END -->", block, txt, flags=re.S)
else:
    txt += "\n## Samples\n\n" + block + "\n"
open(rp, "w").write(txt)
print(f"{len(rows)} samples -> {ROOT}/catalog.csv and README.md")
for r in rows:
    print(f"  {r['model']}/{r['channel']}/{r['sample']}: born {r['born_events']:,} rad {r['rad_events']:,} ({r['n_spin_states']} spin states)")
