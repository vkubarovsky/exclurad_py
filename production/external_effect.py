import numpy as np
M_P = 0.93827208816
MPI2 = 0.1349768 ** 2
E0 = 10.6


def read(path):
    beam, el, pr = [], [], []
    with open(path) as fh:
        for line in fh:
            q = line.split()
            if len(q) != 14:
                continue
            pid, st = int(q[3]), int(q[2])
            p4 = (float(q[6]), float(q[7]), float(q[8]), float(q[9]))
            if pid == 11 and st == 0:
                beam.append(p4)
            elif pid == 11 and st == 1:
                el.append(p4)
            elif pid == 2212:
                pr.append(p4)
    n = min(len(beam), len(el), len(pr))
    return (np.array(beam[:n]), np.array(el[:n]), np.array(pr[:n]))


def observables(beam, el, pr):
    X = np.array([0.0, 0.0, E0, E0 + M_P])[None, :] - el - pr
    v = X[:, 3] ** 2 - np.einsum("ij,ij->i", X[:, :3], X[:, :3]) - MPI2
    t = 2.0 * M_P * (M_P - pr[:, 3])
    return v, -t, beam[:, 3]


